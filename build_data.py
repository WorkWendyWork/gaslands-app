"""Regenerate data.js from gaslands_full_rulebook_compendium.json.

The JSON is the source of truth for rules data. The app loads it as
`const db = {...};` from data.js so it works offline from file:// too.
Run after editing the JSON:  python build_data.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).parent
data = json.loads((ROOT / "gaslands_full_rulebook_compendium.json").read_text(encoding="utf-8"))["gaslands_database"]
# Escape "</" so rule text can never close a <script> tag early.
payload = json.dumps(data, ensure_ascii=False).replace("</", r"<\/")
(ROOT / "data.js").write_text(f"// Generated by build_data.py from gaslands_full_rulebook_compendium.json. Do not edit.\nconst db = {payload};\n", encoding="utf-8")
print("wrote data.js")
